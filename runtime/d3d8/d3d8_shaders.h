"fragment float4 ui_fs(UIOut in [[stage_in]], texture2d<float> icons [[texture(0)]], sampler smp [[sampler(0)]]) {\n"
"  float d = length(in.uv);\n"
"  if (d > 1.0) discard_fragment();\n"
"  float ring = smoothstep(0.82, 0.88, d) * (1.0 - smoothstep(0.95, 1.0, d));\n"
"  float3 c = in.col.rgb;\n"
"  float a = in.pressed > 0 ? 0.55 : 0.18;\n"
"  float3 rgb = c * a;\n"
"  rgb = mix(rgb, c, ring * 0.9); a = max(a, ring * 0.9);\n"
"  if (in.prog > 0) {   /* hold-to-activate progress around the ring */\n"
"    float ang = atan2(in.uv.x, -in.uv.y) / 6.2831853; if (ang < 0) ang += 1.0;\n"
"    float on = ring * step(ang, in.prog); rgb = mix(rgb, float3(1), on); a = max(a, on);\n"
"  }\n"
"  float idx = max(in.icon - 1.0, 0.0);\n"
"  float2 iuv = in.uv / 0.70 * 0.5 + 0.5;\n"
"  float inside = (in.icon > 0.5 && all(iuv >= 0.0) && all(iuv <= 1.0)) ? 1.0 : 0.0;\n"
"  float2 cell = float2(fmod(idx, 4.0), floor(idx / 4.0));\n"
"  float m = icons.sample(smp, (cell + clamp(iuv, 0.0, 1.0)) / float2(4.0, 3.0)).r * inside;\n"
"  float3 ic = in.pressed > 0 ? float3(1) : mix(c, float3(1), 0.55);\n"
"  rgb = mix(rgb, ic, m); a = mix(a, 1.0, m);\n"
"  return float4(rgb * in.col.a, a * in.col.a);\n"
"}\n";
