/* Metal Shading Language source for the D3D8 fixed-function emulation. */
#pragma once

/* Uniform blocks: only float4 / int4 / float4x4 members so C and MSL layouts match. */
typedef struct {
    float wv[16];          /* world*view, column-major for MSL (== D3D row-major memory of W*V) */
    float proj[16];
    float wvp[16];
    float vp[4];           /* viewport x, y, w, h (pixels) */
    float rt[4];           /* render target w, h, minz, maxz */
    float ambient[4];
    float mat_dif[4], mat_amb[4], mat_spc[4], mat_emi[4], mat_pow[4];
    float l_dif[8][4], l_spc[8][4], l_amb[8][4], l_pos[8][4], l_dir[8][4], l_att[8][4], l_spot[8][4];
    int   cfg0[4];         /* nlights, lighting, normalize, localviewer */
    int   cfg1[4];         /* colorvertex, diffuse_src, specular_src, ambient_src */
    int   cfg2[4];         /* emissive_src, specular_enable, fog_mode(0 off,1 exp,2 exp2,3 linear,4 from specular.a), range_fog */
    float fog[4];          /* start, end, density, pointsize */
    int   tci[4];          /* TEXCOORDINDEX per stage */
    int   ttf[4];          /* TEXTURETRANSFORMFLAGS per stage */
    float texm[4][16];
} VSU;

typedef struct {
    int   cop[4][4];       /* colorop, arg1, arg2, arg0 */
    int   aop[4][4];       /* alphaop, arg1, arg2, arg0 */
    int   res[4][4];       /* resultarg, projected, bound, - */
    float tfactor[4];
    float fogcolor[4];
    int   flags[4];        /* alphatest, alphafunc, specular, fog */
    float aref[4];
} FSU;

